BASE = Path(__file__).resolve().parent
MANUAL_DIR = BASE / "data" / "manuals"
WO_DIR = BASE / "data" / "workorders"

pdfmetrics.registerFont(UnicodeCIDFont("STSong-Light"))

STY = getSampleStyleSheet()
H1 = ParagraphStyle("H1", parent=STY["Heading1"], fontName="STSong-Light", fontSize=17,
                    leading=24, spaceAfter=10, textColor=colors.HexColor("#0f172a"))
H2 = ParagraphStyle("H2", parent=STY["Heading2"], fontName="STSong-Light", fontSize=12.5,
                    leading=18, spaceBefore=10, spaceAfter=6, textColor=colors.HexColor("#0369a1"))
BODY = ParagraphStyle("BODY", parent=STY["BodyText"], fontName="STSong-Light", fontSize=9.8,
                      leading=16, spaceAfter=5, alignment=TA_LEFT)
NOTE = ParagraphStyle("NOTE", parent=BODY, fontSize=9, textColor=colors.HexColor("#475569"),
                      leftIndent=8, borderPadding=4)


def table(rows, widths=None, header=True):
    data = [[Paragraph(str(c), BODY) for c in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cbd5e1")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style += [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ]
    t.setStyle(TableStyle(style))
    return t


def build(path: Path, title: str, doc_no: str, pages: list[list]) -> None:
    doc = SimpleDocTemplate(
        str(path), pagesize=A4,
        leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm, bottomMargin=16 * mm,
        title=title, author="开物工业知识中枢演示文档",
    )
    story = []
    for i, blocks in enumerate(pages, 1):
        if i > 1:
            story.append(PageBreak())
        story.append(Paragraph(title, H1))
        story.append(Paragraph(f"文档编号 {doc_no}　｜　第 {i} 页 / 共 {len(pages)} 页　｜　演示用自撰文档，非厂商原文", NOTE))
        story.append(Spacer(1, 8))
        for block in blocks:
            kind = block[0]
            if kind == "h2":
                story.append(Paragraph(block[1], H2))
            elif kind == "p":
                story.append(Paragraph(block[1], BODY))
            elif kind == "table":
                story.append(table(block[1], widths=block[2] if len(block) > 2 else None))
                story.append(Spacer(1, 6))
    doc.build(story)


